/**
 * docs/issues/0061 Option 2 (the four MECHANICAL rows only) — add the missing dialect rows that
 * are straight copies of sibling-type rows:
 *
 *   task/created_by_ref       -> identity            (event/impact have it in the same file)
 *   sequence/created_by_ref   -> identity            (same)
 *   anecdote/provided_by_ref  -> identity            (the os-threat anecdote SCO's own property)
 *   anecdote/object_marking_refs -> marking-definition
 *
 * ⚠️ relationship/source_ref + target_ref are DELIBERATELY not added: STIX constrains the pair by
 * relationship type, which this flat map cannot express — `_any` is honest but permissive, and
 * 0061 records it as the os-threat team's call. Proposed, not improvised.
 *
 * Edits extensions/connections.json AND mirrors into summary/connections.json (the summary is
 * generated by generate_summary.ipynb; mirroring keeps them consistent so a regen is a no-op for
 * these rows). Text surgery with CRLF + 4-space indent matching the files; count-asserted.
 *
 *     node e2e/fix-0061-add-dialect-rows.mjs [--apply]
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const APPLY = process.argv.includes('--apply')
const WORKSPACE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const DIALECT = path.join(WORKSPACE, 'typerefinery/services/fastapi/generated/os-triage/dialect_data')

const CRLF = '\r\n'
const row = (source, field, target, desc) =>
  [
    '    {',
    `        "source_type": "${source}",`,
    `        "field": "${field}",`,
    `        "target_type": "${target}",`,
    `        "description": "${desc}"`,
    '    },',
  ].join(CRLF)

const CREATED_DESC =
  'The created_by_ref property specifies the id property of the identity object that describes the entity that created this object.'
const MARKING_DESC =
  'The object_marking_refs property specifies a list of id properties of marking-definition objects that apply to this object.'
const PROVIDED_DESC =
  'The provided_by_ref property specifies the id property of the identity object that provided this anecdote.'

const ROWS = [
  row('task', 'created_by_ref', 'identity', CREATED_DESC),
  row('sequence', 'created_by_ref', 'identity', CREATED_DESC),
  row('anecdote', 'provided_by_ref', 'identity', PROVIDED_DESC),
  row('anecdote', 'object_marking_refs', 'marking-definition', MARKING_DESC),
].join(CRLF)

for (const rel of ['extensions/connections.json', 'summary/connections.json']) {
  const file = path.join(DIALECT, rel)
  let raw = fs.readFileSync(file, 'utf8')
  const before = JSON.parse(raw).length
  for (const pair of [
    ['task', 'created_by_ref'],
    ['sequence', 'created_by_ref'],
    ['anecdote', 'provided_by_ref'],
    ['anecdote', 'object_marking_refs'],
  ]) {
    const exists = JSON.parse(raw).some((r) => r.source_type === pair[0] && r.field === pair[1])
    if (exists) {
      console.log(`  = ${rel}: ${pair.join('/')} already present — skipped`)
      continue
    }
  }
  // insert the block after the FIRST "source_type": "task" row's opening — simplest safe spot:
  // right after the opening bracket line, at the head of the array (order carries no meaning in
  // this map; the consumer filters by source_type+field).
  const anchor = '[' + CRLF + '    {'
  if (!raw.startsWith(anchor)) {
    console.log(`🔴 ${rel}: unexpected head — refusing`)
    process.exitCode = 1
    continue
  }
  const out = '[' + CRLF + ROWS + CRLF + '    {' + raw.slice(anchor.length)
  const parsed = JSON.parse(out)
  const added = parsed.length - before
  console.log(`== ${rel}: ${before} -> ${parsed.length} entries (+${added})`)
  if (added !== 4) {
    console.log('🔴 expected +4 — refusing')
    process.exitCode = 1
    continue
  }
  if (APPLY) {
    fs.writeFileSync(file, out)
    console.log(`✅ written`)
  } else {
    console.log('   (dry run)')
  }
}
