/**
 * Prune the Promotable pane down by removing objects **our own test code demonstrably created** —
 * docs/issues/0138 phase 2, the prune third.
 *
 * 🔑 **This is the INVERSE of the heuristic 0138 rejected, and that is the whole point.**
 *
 * The rejected approach was *"keep what matches image5's narrative, delete the rest"*. It was
 * disproved on its own output: it missed `Sighting-Alert` over a hyphen, and it would have deleted
 * the 30-odd identities including **`Naive Smith`, the story's own victim**. Asking *"does this look
 * like narrative content?"* is a question no pattern can answer safely, because a false negative
 * deletes the demo.
 *
 * This script asks the opposite, answerable question: **"did our committed test code generate this
 * exact name?"** A false negative here merely leaves an object on the pane — visible, harmless, and
 * fixable by a human. Nothing in the narrative can be deleted by a rule that only ever matches
 * strings our own harness prints.
 *
 * Every pattern must cite the file:line that produces it. A pattern with no citation is reported
 * under a separate, explicitly weaker heading rather than being quietly folded in with the rest.
 *
 * ⚠️ **Fully reversible.** `unattached_objs.json` is a *tracked* file in the `stix2-demo-context`
 * submodule, so `git checkout -- <file>` restores it exactly. That is why this is safe to run in a
 * way that deleting untracked content would not be.
 *
 *     node e2e/prune-harness-debris.mjs                # dry run (default) — prints the verdict table
 *     node e2e/prune-harness-debris.mjs --apply
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const WORKSPACE = path.resolve(__dirname, '..', '..')
const CONTEXT = path.join(
  WORKSPACE,
  'typerefinery/services/fastapi/generated/os-triage/context_mem',
)
const APPLY = process.argv.includes('--apply')

/**
 * Patterns whose generator is in **committed** code. Each cites the file:line that prints it, so a
 * reviewer can check the claim rather than trust it.
 */
const ATTRIBUTED = [
  { re: /^Scratch fixture \d{2}:\d{2}:\d{2}$/, from: 'e2e/fixtures.ts:46' },
  { re: /^Runsheet identity \d{2}:\d{2}:\d{2}$/, from: 'e2e/specs/05-forms.spec.ts:87' },
  { re: /^Runsheet identity ext \d{2}:\d{2}:\d{2}$/, from: 'e2e/specs/05-forms.spec.ts:146' },
  { re: /^Runsheet probe \d{2}:\d{2}:\d{2}$/, from: 'e2e/specs/01-incidents.spec.ts:339' },
  { re: /^Runsheet nav \d{2}:\d{2}:\d{2}$/, from: 'e2e/specs/01-incidents.spec.ts:449' },
  { re: /^Runsheet failure probe/, from: 'e2e/specs/01-incidents.spec.ts:574' },
  { re: /^Runsheet identity \d{2}:\d{2}:\d{2}$/, from: 'e2e/seed-scratch-objects.mjs:14' },
]

/**
 * Weaker: the name ends in a bare `HH:MM:SS` clock time and no committed generator produces it —
 * i.e. an ad-hoc diagnostic script that was never checked in (`Diag identity 05:38:01`).
 *
 * Reported SEPARATELY and never merged into the attributed count. The justification is only that no
 * curated narrative object is named after a wall-clock time, which is weaker evidence than a cited
 * generator, so a human should be able to see exactly which deletions rest on it.
 */
const UNATTRIBUTED_SHAPE = /\b\d{2}:\d{2}:\d{2}$/

const nameOf = (o) =>
  o.name ?? o.value ?? o.account_login ?? o.display_name ?? ''

const classify = (o) => {
  const name = nameOf(o)
  if (!name) return { verdict: 'keep', why: 'no name field to match on' }
  for (const p of ATTRIBUTED) {
    if (p.re.test(name)) return { verdict: 'prune', why: `generated by ${p.from}`, attributed: true }
  }
  if (UNATTRIBUTED_SHAPE.test(name)) {
    return { verdict: 'prune', why: 'ends in a wall-clock time; NO committed generator', attributed: false }
  }
  return { verdict: 'keep', why: 'no harness pattern matches' }
}

let totalPruned = 0
for (const dir of fs.readdirSync(CONTEXT).filter((d) => d.startsWith('incident--'))) {
  const file = path.join(CONTEXT, dir, 'unattached_objs.json')
  if (!fs.existsSync(file)) continue

  const objects = JSON.parse(fs.readFileSync(file, 'utf8'))
  if (!Array.isArray(objects)) {
    console.error(`  SKIP ${dir} — unattached_objs.json is not an array; refusing to guess its shape`)
    continue
  }

  const verdicts = objects.map((o) => ({ o, ...classify(o) }))
  const prune = verdicts.filter((v) => v.verdict === 'prune')
  const attributed = prune.filter((v) => v.attributed)

  console.log(`\n=== ${dir} ===`)
  console.log(`  ${objects.length} Promotable objects -> keep ${objects.length - prune.length}, prune ${prune.length}`)
  console.log(`     of which attributed to a cited generator: ${attributed.length}`)
  console.log(`     resting on the weaker shape rule        : ${prune.length - attributed.length}`)

  for (const v of prune) {
    console.log(`  ${v.attributed ? 'PRUNE ' : 'PRUNE?'} ${v.o.type.padEnd(14)} ${nameOf(v.o).padEnd(34)} ${v.why}`)
  }

  // 🔑 The safety assertion that matters: name the narrative objects that SURVIVE, so a reviewer
  // sees Naive Smith in the keep list rather than having to trust that the rule spared them.
  const keptNamed = verdicts.filter((v) => v.verdict === 'keep' && nameOf(v.o))
  console.log(`  -- kept, named (${keptNamed.length}) --`)
  console.log(`     ${keptNamed.map((v) => nameOf(v.o)).join(' · ')}`)

  totalPruned += prune.length
  if (!APPLY) continue

  const remaining = verdicts.filter((v) => v.verdict === 'keep').map((v) => v.o)
  fs.writeFileSync(file, JSON.stringify(remaining, null, 2))
  console.log(`  WROTE ${objects.length} -> ${remaining.length} objects`)
}

console.log(
  APPLY
    ? `\napplied — ${totalPruned} object(s) removed. Reversible: git checkout -- <unattached_objs.json> in the submodule.`
    : `\ndry run — ${totalPruned} object(s) WOULD be removed. Re-run with --apply.`,
)
